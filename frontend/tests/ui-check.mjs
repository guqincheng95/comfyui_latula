// Reproducible headless checks against the local protocol fixture.
// No private browsing session, GPU model, paid API or real AI output is used.
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'..')
await fs.mkdir(path.join(root,'test-results'),{recursive:true})
await fs.writeFile(path.join(root,'tests/fixtures/input.svg'),'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><rect width="64" height="64" fill="#d4a45f"/></svg>')
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE || undefined,args:['--no-sandbox']})
const errors=[]
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1})
const page=await context.newPage()
page.on('pageerror',error=>errors.push(error.message))
await page.goto('http://127.0.0.1:5173')
await page.getByRole('button',{name:'装配工作流',exact:true}).waitFor()
await page.screenshot({path:path.join(root,'test-results/home-390.png'),fullPage:true})
await page.getByRole('button',{name:'进入工作流',exact:true}).click()
await page.getByRole('button',{name:'导入 ComfyUI 工作流',exact:true}).waitFor()
await page.getByRole('button',{name:'导入 ComfyUI 工作流',exact:true}).click()
await page.getByLabel('工作流名称',{exact:true}).fill('协议验证工作流')
await page.getByLabel('ComfyUI 服务地址',{exact:true}).fill('http://127.0.0.1:5173/mock')
await page.getByLabel('导入 API 工作流文件').setInputFiles(path.join(root,'tests/fixtures/basic-api.json'))
await page.getByRole('button',{name:'测试连接 · 完善自动装配'}).click()
await page.getByRole('button',{name:'测试连接 · 完善自动装配'}).waitFor()
await page.getByLabel('工作流名称',{exact:true}).fill('协议验证工作流')
await page.screenshot({path:path.join(root,'test-results/assembly-390.png'),fullPage:true})
await page.getByRole('button',{name:'保存并装配',exact:true}).click()
await page.locator('.assembly-sign.equipped').waitFor()
await page.getByRole('button',{name:'进入工作流',exact:true}).click()
await page.getByLabel('正向提示词').fill('自动装配测试：一只猫咪')
await page.getByLabel('参考图片',{exact:true}).setInputFiles(path.join(root,'tests/fixtures/input.svg'))
await page.getByLabel('采样步数').fill('12')
await page.screenshot({path:path.join(root,'test-results/workbench-390.png'),fullPage:true})
await page.getByRole('button',{name:'提交工作流',exact:true}).click()
await page.getByRole('heading',{name:'已完成',exact:true}).waitFor({timeout:30000})
await page.getByRole('button',{name:'查看任务',exact:true}).click()
await page.locator('.output-card img').waitFor()
await page.getByRole('button',{name:'收藏任务',exact:true}).click()
await page.screenshot({path:path.join(root,'test-results/result-390.png'),fullPage:true})
const captured=await (await fetch('http://127.0.0.1:5173/test-captured')).json()
const jobs=Object.values(captured)
assert.equal(jobs.length,1,'only one task should be submitted')
assert.equal(jobs[0].request.prompt['2'].inputs.text,'自动装配测试：一只猫咪')
assert.equal(jobs[0].request.prompt['4'].inputs.steps,12)
assert.equal(jobs[0].request.prompt['1'].inputs.image,'latula/uploaded-reference.png')
assert.deepEqual(jobs[0].request.prompt['4'].inputs.positive,['2',0])
await page.getByRole('button',{name:'使用相同参数',exact:true}).click()
await page.getByRole('button',{name:'提交工作流',exact:true}).waitFor()
assert.equal(await page.getByLabel('正向提示词').inputValue(),'自动装配测试：一只猫咪')
assert.equal(Object.keys(await (await fetch('http://127.0.0.1:5173/test-captured')).json()).length,1,'reuse must not auto-submit')
await page.reload()
await page.locator('.assembly-sign.equipped').waitFor()
await page.getByRole('button',{name:'历史任务',exact:true}).click()
await page.locator('.history-card').waitFor()
await page.getByLabel('只看收藏').check()
assert.equal(await page.locator('.history-card').count(),1)
await page.screenshot({path:path.join(root,'test-results/history-390.png'),fullPage:true})
for(const [width,height] of [[360,640],[430,932]]){
 await page.getByRole('button',{name:'返回主页',exact:true}).click().catch(()=>{})
 await page.setViewportSize({width,height})
 await page.getByRole('button',{name:'进入工作流',exact:true}).waitFor()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'home should not overflow viewport')
 await page.screenshot({path:path.join(root,'test-results/home-'+width+'.png'),fullPage:true})
 await page.getByRole('button',{name:'进入工作流',exact:true}).click()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'workbench should not overflow viewport')
 await page.screenshot({path:path.join(root,'test-results/workbench-'+width+'.png'),fullPage:true})
}
assert.deepEqual(errors,[],'no uncaught runtime errors')
console.log('PASS: import → schema assembly → material upload → one submission → result → favorite → reuse without resubmit → reload persistence; 360/390/430px layouts; no page errors.')
await browser.close()
